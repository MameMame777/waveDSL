#[cfg(test)]
mod tests {
    use super::*;
    use crate::error::Span;

    fn sp() -> Span { Span::new(1, 1) }

    fn num_arg(n: u64) -> Arg { Arg::Positional(Value::Number(n), sp()) }
    fn str_arg(s: &str) -> Arg { Arg::Positional(Value::Str(s.to_string()), sp()) }

    fn call(name: &str, args: Vec<Arg>) -> WaveExpr {
        WaveExpr::Call { name: name.to_string(), args, span: sp() }
    }

    #[test]
    fn test_eval_low_high_low() {
        let seq = vec![
            call("low",  vec![num_arg(2)]),
            call("high", vec![num_arg(4)]),
            call("low",  vec![num_arg(2)]),
        ];
        let states = eval_waveform(&seq);
        assert_eq!(states.len(), 8);
        assert_eq!(states[0], WaveState::Low);
        assert_eq!(states[2], WaveState::High);
        assert_eq!(states[6], WaveState::Low);
    }

    #[test]
    fn test_eval_data_label() {
        let seq = vec![
            call("x",    vec![num_arg(2)]),
            call("data", vec![num_arg(4), str_arg("0xAB")]),
            call("x",    vec![num_arg(2)]),
        ];
        let states = eval_waveform(&seq);
        assert_eq!(states[2], WaveState::Data("0xAB".to_string()));
        assert_eq!(states[5], WaveState::Data("0xAB".to_string()));
        assert_eq!(states[6], WaveState::X);
    }

    #[test]
    fn test_detect_trigger_rose() {
        let wf = vec![
            WaveState::Low, WaveState::Low,
            WaveState::High, WaveState::High, WaveState::High, WaveState::High,
            WaveState::Low, WaveState::Low,
        ];
        let result = detect_trigger(&[wf]);
        assert!(matches!(result, Some((0, 2, TriggerKind::Rose))));
    }

    #[test]
    fn test_detect_trigger_fell() {
        let wf = vec![WaveState::High, WaveState::High, WaveState::Low, WaveState::Low];
        let result = detect_trigger(&[wf]);
        assert!(matches!(result, Some((0, 2, TriggerKind::Fell))));
    }

    #[test]
    fn test_detect_trigger_none() {
        let wf = vec![WaveState::X, WaveState::X, WaveState::X];
        assert!(detect_trigger(&[wf]).is_none());
    }

    #[test]
    fn test_compress_conditions() {
        let conds = vec![
            "a == 1".to_string(), "a == 1".to_string(),
            "a == 1".to_string(), "b == 0".to_string(),
        ];
        let c = compress_conditions(&conds);
        assert_eq!(c.len(), 2);
        assert_eq!(c[0], ("a == 1".to_string(), 3));
        assert_eq!(c[1], ("b == 0".to_string(), 1));
    }

    #[test]
    fn test_parse_hex_digits() {
        assert_eq!(parse_hex_digits("0xAB"), Some("AB"));
        assert_eq!(parse_hex_digits("0xFF"), Some("FF"));
        assert_eq!(parse_hex_digits("0X1A"), Some("1A"));
        assert_eq!(parse_hex_digits("CMD"),  None);
        assert_eq!(parse_hex_digits("0x"),   None); // empty hex
    }

    #[test]
    fn test_state_to_sv_cond() {
        assert_eq!(
            state_to_sv_cond("valid", &WaveState::High),
            Some("valid == 1'b1".to_string())
        );
        assert_eq!(
            state_to_sv_cond("d", &WaveState::Data("0xAB".to_string())),
            Some("d == 8'hAB".to_string())
        );
        assert_eq!(
            state_to_sv_cond("d", &WaveState::Data("CMD".to_string())),
            Some("(d !== 'x && d !== 'z)".to_string())
        );
        assert_eq!(state_to_sv_cond("s", &WaveState::X), None);
    }

    #[test]
    fn test_cond_expr_to_sv_compare() {
        let e = CondExpr::Compare {
            signal: "valid".to_string(), op: CmpOp::Eq, state: StateVal::High, span: sp(),
        };
        assert_eq!(cond_expr_to_sv(&e), "valid == 1'b1");
    }

    #[test]
    fn test_cond_expr_to_sv_sysfunc() {
        let e = CondExpr::SysFunc { func: SysFunc::Rose, signal: "clk".to_string(), span: sp() };
        assert_eq!(cond_expr_to_sv(&e), "$rose(clk)");
    }

    #[test]
    fn test_seq_expr_delay() {
        let inner = SeqExpr::Cond(CondExpr::Compare {
            signal: "d".to_string(), op: CmpOp::Ne, state: StateVal::X, span: sp(),
        });
        let e = SeqExpr::Delay { cycles: 2, expr: Box::new(inner), span: sp() };
        assert_eq!(seq_expr_to_sv(&e), "##2 (d !== 'x)");
    }
}
